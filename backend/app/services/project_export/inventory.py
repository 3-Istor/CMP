"""
What the platform holds for a project, and whether an export carries it.

This is the exhaustive list the EU Data Act (Art. 25(2)(e)) asks the provider
to publish; the French page "Réversibilité et portabilité" in cnp-docs
renders the same list. Every CMP table is classified here, exported or not
with a reason: a test fails when a new table is not.
"""

from collections.abc import Callable
from dataclasses import dataclass

from sqlalchemy import ColumnElement, Table, and_, false, select


@dataclass(frozen=True)
class TableSpec:
    """How to select one project's rows, and the columns never exported."""

    where: Callable[[Table, str, list[int]], ColumnElement[bool]]
    drop: tuple[str, ...] = ()


def _by(column: str) -> Callable[[Table, str, list[int]], ColumnElement]:
    return lambda table, project, _ids: table.c[column] == project


def _by_deployment(
    table: Table, _project: str, ids: list[int]
) -> ColumnElement[bool]:
    return table.c.deployment_id.in_(ids) if ids else false()


def _project_review_items(
    table: Table, project: str, _ids: list[int]
) -> ColumnElement[bool]:
    return and_(table.c.scope == "project", table.c.subject == project)


def _by_import_source(
    table: Table, project: str, _ids: list[int]
) -> ColumnElement[bool]:
    sources = table.metadata.tables["import_sources"]
    return table.c.source_id.in_(
        select(sources.c.id).where(sources.c.project_name == project)
    )


